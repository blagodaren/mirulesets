package model

import "time"

type Source struct {
	ID       string `json:"id,omitempty"`
	Name     string `json:"name"`
	URL      string `json:"url"`
	Format   string `json:"format"`
	Behavior string `json:"behavior"`
	Enabled  bool   `json:"enabled"`
	// Headers are stored with state.json but removed from every public/admin DTO.
	Headers      map[string]string `json:"headers,omitempty"`
	HeaderNames  []string          `json:"headerNames,omitempty"`
	ClearHeaders bool              `json:"clearHeaders,omitempty"`
	IncludeRegex string            `json:"includeRegex,omitempty"`
	ExcludeRegex string            `json:"excludeRegex,omitempty"`
	Selector     string            `json:"selector,omitempty"`
	Status       *SourceStatus     `json:"status,omitempty"`
}

type SourceStatus struct {
	CheckedAt  time.Time `json:"checkedAt"`
	FetchedAt  time.Time `json:"fetchedAt,omitempty"`
	RuleCount  int       `json:"ruleCount"`
	HTTPStatus int       `json:"httpStatus,omitempty"`
	Error      string    `json:"error,omitempty"`
}

type Ruleset struct {
	RollbackHold    bool      `json:"rollbackHold,omitempty"`
	RollbackUntil   time.Time `json:"rollbackUntil,omitempty"`
	MaxDropPercent  *float64  `json:"maxDropPercent,omitempty"`
	Tags            []string  `json:"tags,omitempty"`
	ID              string    `json:"id"`
	Name            string    `json:"name"`
	Behavior        string    `json:"behavior"`
	Policy          string    `json:"policy"`
	Sources         []Source  `json:"sources"`
	CustomRules     []string  `json:"customRules"`
	ExcludeRules    []string  `json:"excludeRules"`
	IntervalSeconds int       `json:"intervalSeconds"`
	Formats         []string  `json:"formats"`
	Enabled         bool      `json:"enabled"`
	Revision        int       `json:"revision"`
	UpdatedAt       time.Time `json:"updatedAt"`
	LastBuild       *Build    `json:"lastBuild,omitempty"`
	LastError       string    `json:"lastError,omitempty"`
}

type Artifact struct {
	S3Published bool   `json:"s3Published,omitempty"`
	S3Error     string `json:"s3Error,omitempty"`
	Format      string `json:"format"`
	URL         string `json:"url"`
	Size        int    `json:"size"`
	SHA256      string `json:"sha256"`
	S3URL       string `json:"s3Url,omitempty"`
}

type Build struct {
	CanonicalSHA256 string     `json:"canonicalSha256,omitempty"`
	Behavior        string     `json:"behavior,omitempty"`
	Added           int        `json:"added"`
	Removed         int        `json:"removed"`
	BuiltAt         time.Time  `json:"builtAt"`
	RuleCount       int        `json:"ruleCount"`
	SourceCount     int        `json:"sourceCount"`
	DurationMS      int64      `json:"durationMs"`
	Revision        int        `json:"revision"`
	Files           []Artifact `json:"files"`
	// Generation selects a complete immutable artifact directory.
	Generation         string `json:"generation"`
	PreviousGeneration string `json:"previousGeneration,omitempty"`
	// S3Target fingerprints the destination; failed uploads remain retryable even
	// when generated bytes and the local generation have not changed.
	S3Target    string `json:"s3Target,omitempty"`
	S3Published bool   `json:"s3Published,omitempty"`
}

type Event struct {
	Time      time.Time `json:"time"`
	Level     string    `json:"level"`
	Message   string    `json:"message"`
	RulesetID string    `json:"rulesetId,omitempty"`
}

type State struct {
	S3DeleteTargets  map[string]string `json:"s3DeleteTargets,omitempty"`
	PendingS3Deletes []string          `json:"pendingS3Deletes,omitempty"`
	Version          int               `json:"version"`
	Rulesets         []Ruleset         `json:"rulesets"`
}
